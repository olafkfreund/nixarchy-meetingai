//! Hyprland shortcuts.
//!
//! Hyprland replaced `hyprctl keyword bind` with a Lua config in 0.55, and the
//! portal path is unavailable on some systems. Hyprland's own config is therefore
//! the reliable route: lennette writes a small Lua module declaring its bindings
//! and tells the user to `require` it.
//!
//! Bindings live in your config, so they survive restarts and are visible in your
//! own dotfiles, exactly like any other keybind.

use std::path::{Path, PathBuf};

use crate::platform::shortcuts::{Action, Binding};

/// Whether Hyprland is the running compositor.
pub fn is_hyprland() -> bool {
    let env_set = std::env::var_os("HYPRLAND_INSTANCE_SIGNATURE").is_some();
    if env_set {
        return true;
    }
    // Fall back to asking the compositor directly.
    std::process::Command::new("hyprctl")
        .arg("version")
        .output()
        .map(|output| output.status.success())
        .unwrap_or(false)
}

/// Where Hyprland's config lives.
pub fn config_directory() -> Option<PathBuf> {
    let config = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .or_else(|| directories::BaseDirs::new().map(|dirs| dirs.config_dir().to_path_buf()))?;
    let hypr = config.join("hypr");
    hypr.is_dir().then_some(hypr)
}

/// The file lennette owns inside the Hyprland config directory.
pub fn include_path(directory: &Path) -> PathBuf {
    directory.join("lennette.lua")
}

/// The shell command one action runs.
pub fn command(action: Action) -> &'static str {
    match action {
        Action::ToggleDashboard => "lennette --toggle-dashboard",
        Action::ToggleWindow => "lennette --toggle-window",
        Action::FocusInput => "lennette --focus-input",
        Action::SystemAudio => "lennette --toggle-system-audio",
        Action::VoiceInput => "lennette --toggle-voice",
        Action::Screenshot => "lennette --screenshot",
    }
}

/// Convert a binding into Hyprland's `MODS + KEY` notation.
///
/// Hyprland uses `+` between parts and names keys as written, so `CTRL + SHIFT + D`.
pub fn accelerator(binding: &Binding) -> String {
    let mut parts = Vec::new();
    if binding.ctrl {
        parts.push("CTRL");
    }
    if binding.shift {
        parts.push("SHIFT");
    }
    if binding.alt {
        parts.push("ALT");
    }
    let key = match binding.key.as_str() {
        "backslash" if binding.shift => "code:51".to_owned(),
        "backslash" => "backslash".to_owned(),
        "space" => "space".to_owned(),
        "enter" => "Return".to_owned(),
        other => other.to_uppercase(),
    };
    parts.push(&key);
    parts.join(" + ")
}

/// Window rules so the overlay is drawn by lennette, not by Hyprland.
///
/// A compositor border or rounding would fight the overlay's own glass edge, so
/// both are disabled and the window floats without decorations.
pub fn window_rules() -> &'static str {
    // Effects are flat in this Hyprland build; a nested `effect = {}` table is
    // rejected with "unknown field 'effect'".
    "hl.window_rule({\n\
     \x20   match = { class = \"lennette\" },\n\
     \x20   float = true,\n\
     \x20   pin = true,\n\
     \x20   border_size = 0,\n\
     \x20   rounding = 0,\n\
     \x20   no_blur = true,\n\
     })\n\
     hl.window_rule({\n\
     \x20   match = { title = \"lennette\" },\n\
     \x20   float = true,\n\
     \x20   pin = true,\n\
     \x20   border_size = 0,\n\
     \x20   rounding = 0,\n\
     \x20   no_blur = true,\n\
     })\n\
     hl.window_rule({\n\
     \x20   match = { class = \"dev.lennette.overlay\" },\n\
     \x20   float = true,\n\
     \x20   pin = true,\n\
     \x20   border_size = 0,\n\
     \x20   rounding = 0,\n\
     \x20   no_blur = true,\n\
     })\n\
     hl.window_rule({ match = { class = \"dev.lennette.overlay\", title = \"^lennette$\" }, size = {720, 620}, center = true })\n\
     hl.window_rule({ match = { class = \"dev.lennette.overlay\", title = \"^lennette dashboard$\" }, size = {1100, 760}, center = true })\n"
}

/// Generate the Lua module contents.
pub fn lua_module(bindings: &[Binding]) -> String {
    let mut out = String::from(
        "-- Generated by lennette. Edit the bindings in lennette's settings instead.\n\
         -- Add this to your hyprland.lua:  require(\"lennette\")\n\n",
    );
    for binding in bindings {
        out.push_str(&format!(
            "hl.bind(\"{}\", hl.dsp.exec_cmd(\"{}\"))\n",
            accelerator(binding),
            command(binding.action)
        ));
    }
    out.push('\n');
    out.push_str(window_rules());
    out
}

/// Write the module, returning its path.
pub fn install(bindings: &[Binding]) -> Result<PathBuf, String> {
    let directory =
        config_directory().ok_or_else(|| "no Hyprland config directory was found".to_owned())?;
    let path = include_path(&directory);
    std::fs::write(&path, lua_module(bindings)).map_err(|error| error.to_string())?;
    Ok(path)
}

/// The exact line to add to `hyprland.lua`.
pub fn required_line() -> &'static str {
    "safe_require(\"lennette\")"
}

/// Whether the user's `hyprland.lua` already requires the module.
pub fn is_required(directory: &Path) -> bool {
    let config = directory.join("hyprland.lua");
    std::fs::read_to_string(config)
        .map(|text| {
            text.contains("require(\"lennette\")")
                || text.contains("require('lennette')")
                || text.contains(required_line())
        })
        .unwrap_or(false)
}

/// Apply window rules and bindings to the running compositor with `hyprctl eval`.
///
/// This makes them work immediately; the written module makes them survive a
/// restart.
pub fn apply_now(bindings: &[Binding]) -> Result<usize, String> {
    // This runs before open_window. Writing lennette.lua alone leaves the
    // first launch tiled until the user reloads the compositor configuration.
    apply_expression(window_rules())?;
    let mut applied = 0;
    for binding in bindings {
        let expression = format!(
            "hl.bind(\"{}\", hl.dsp.exec_cmd(\"{}\"))",
            accelerator(binding),
            command(binding.action)
        );
        apply_expression(&expression)?;
        applied += 1;
    }
    Ok(applied)
}

fn apply_expression(expression: &str) -> Result<(), String> {
    let output = std::process::Command::new("hyprctl")
        .args(["eval", expression])
        .output()
        .map_err(|error| format!("hyprctl is unavailable: {error}"))?;
    let stdout = String::from_utf8_lossy(&output.stdout);
    if !output.status.success() || stdout.trim() != "ok" {
        return Err(format!("hyprctl rejected configuration: {}", stdout.trim()));
    }
    Ok(())
}

/// Keep the protected Nix launcher when repairing the shifted physical key.
pub fn repair_managed_toggle() -> Result<(), String> {
    apply_expression(
        r#"hl.window_rule({name="lennette-clear-glass",match={class=[[^(dev\.lennette\.overlay|lennette)$]]},no_blur=true})"#,
    )?;
    let path = config_directory().ok_or("Hyprland configuration not found")?;
    let text = std::fs::read_to_string(include_path(&path)).map_err(|e| e.to_string())?;
    let Some(binding) = text.lines().find(|line| {
        (line.contains("CTRL + SHIFT + backslash") || line.contains("CTRL + SHIFT + code:51"))
            && line.contains("lennette-private")
            && line.contains("--toggle-window")
    }) else {
        return Ok(());
    };
    // A keysym binding and a physical binding can both match the same stroke.
    // Replace both forms atomically so one keypress never toggles twice.
    let replacement = binding.replace("CTRL + SHIFT + backslash", "CTRL + SHIFT + code:51");
    apply_expression(&format!(
        r#"hl.unbind("CTRL + SHIFT + backslash"); hl.unbind("CTRL + SHIFT + code:51"); {replacement}"#
    ))
}

/// Park the protected surface on an unopened workspace, retaining its contents.
pub fn set_overlay_visible(visible: bool) -> Result<(), String> {
    let workspace = if visible {
        let output = std::process::Command::new("hyprctl")
            .args(["-j", "activeworkspace"])
            .output()
            .map_err(|e| e.to_string())?;
        let value: serde_json::Value =
            serde_json::from_slice(&output.stdout).map_err(|e| e.to_string())?;
        value["id"]
            .as_i64()
            .ok_or("No active workspace")?
            .to_string()
    } else {
        "special:lennette-hidden".to_owned()
    };
    let workspace = serde_json::to_string(&workspace).map_err(|e| e.to_string())?;
    let selector = r#"window="title:^lennette$""#;
    let expression = format!(
        "hl.dispatch(hl.dsp.window.pin({{{selector},action=\"disable\"}})); hl.dispatch(hl.dsp.window.move({{{selector},workspace={workspace},follow=false}}))"
    );
    apply_expression(&expression)?;
    if visible {
        apply_expression(&format!(
            "hl.dispatch(hl.dsp.window.pin({{{selector},action=\"enable\"}}))"
        ))?;
        focus_overlay();
    }
    Ok(())
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct OverlayGeometry {
    pub x: f32,
    pub y: f32,
    pub width: f32,
    pub height: f32,
}

pub fn overlay_geometry() -> Option<OverlayGeometry> {
    let output = std::process::Command::new("hyprctl")
        .args(["-j", "clients"])
        .output()
        .ok()?;
    let clients: serde_json::Value = serde_json::from_slice(&output.stdout).ok()?;
    let window = clients
        .as_array()?
        .iter()
        .find(|w| w["class"] == "dev.lennette.overlay" && w["title"] == "lennette")?;
    Some(OverlayGeometry {
        x: window["at"][0].as_f64()? as f32,
        y: window["at"][1].as_f64()? as f32,
        width: window["size"][0].as_f64()? as f32,
        height: window["size"][1].as_f64()? as f32,
    })
}

pub fn place_overlay(geometry: OverlayGeometry) -> Result<(), String> {
    apply_expression(&format!(
        "hl.dispatch(hl.dsp.window.resize({{window=\"title:^lennette$\",x={},y={}}})); hl.dispatch(hl.dsp.window.move({{window=\"title:^lennette$\",x={},y={}}}))",
        geometry.width, geometry.height, geometry.x, geometry.y
    ))
}

pub fn dock_geometry(expanded: bool) -> Option<OverlayGeometry> {
    let output = std::process::Command::new("hyprctl")
        .args(["-j", "monitors"])
        .output()
        .ok()?;
    let monitors: serde_json::Value = serde_json::from_slice(&output.stdout).ok()?;
    let monitor = monitors.as_array()?.iter().find(|m| m["focused"] == true)?;
    let scale = monitor["scale"].as_f64()?.max(0.1) as f32;
    let mut width = monitor["width"].as_f64()? as f32 / scale;
    let mut height = monitor["height"].as_f64()? as f32 / scale;
    if matches!(monitor["transform"].as_i64().unwrap_or(0), 1 | 3 | 5 | 7) {
        std::mem::swap(&mut width, &mut height);
    }
    let left = monitor["x"].as_f64()? as f32;
    let top = monitor["y"].as_f64()? as f32
        + monitor["reserved"][1].as_f64().unwrap_or(0.0) as f32
        + 16.0;
    let panel_width = if expanded { 720.0_f32 } else { 560.0_f32 }.min(width - 32.0);
    Some(OverlayGeometry {
        x: left
            + if expanded {
                (width - panel_width) / 2.0
            } else {
                width - panel_width - 16.0
            },
        y: top,
        width: panel_width,
        height: if expanded {
            (height - 100.0).min(620.0)
        } else {
            64.0
        },
    })
}

/// Focus and raise the overlay window in Hyprland.
pub fn focus_overlay() {
    if !is_hyprland() {
        return;
    }
    // bring_to_top operates on the focused window and takes no selector. Check
    // the reply too: hyprctl can report a Lua error with a successful exit code.
    for expression in [
        "hl.dispatch(hl.dsp.focus({ window = \"title:^lennette$\" }))",
        "hl.dispatch(hl.dsp.window.bring_to_top())",
    ] {
        match std::process::Command::new("hyprctl")
            .args(["eval", expression])
            .output()
        {
            Ok(output)
                if output.status.success()
                    && String::from_utf8_lossy(&output.stdout).trim() == "ok" => {}
            Ok(output) => {
                tracing::warn!(reply = %String::from_utf8_lossy(&output.stdout).trim(), "Hyprland could not focus the overlay");
                break;
            }
            Err(error) => {
                tracing::warn!(%error, "hyprctl is unavailable");
                break;
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn accelerators_use_hyprland_notation() {
        let binding = Binding::parse(Action::ToggleDashboard, "ctrl+shift+d").unwrap();
        assert_eq!(accelerator(&binding), "CTRL + SHIFT + D");

        let backslash = Binding::parse(Action::ToggleWindow, "ctrl+backslash").unwrap();
        assert_eq!(accelerator(&backslash), "CTRL + backslash");
        let shifted = Binding::parse(Action::ToggleWindow, "ctrl+shift+backslash").unwrap();
        assert_eq!(accelerator(&shifted), "CTRL + SHIFT + code:51");
    }

    #[test]
    fn module_contains_every_binding() {
        let bindings = Binding::defaults();
        let module = lua_module(&bindings);
        assert!(module.contains("require(\"lennette\")"));
        for binding in &bindings {
            assert!(
                module.contains(&accelerator(binding)),
                "missing {}",
                accelerator(binding)
            );
        }
        // Six bindings means six hl.bind calls.
        assert_eq!(module.matches("hl.bind(").count(), bindings.len());
    }

    #[test]
    fn module_disables_compositor_borders() {
        let module = lua_module(&Binding::defaults());
        assert!(module.contains("border_size = 0"));
        assert!(module.contains("float = true"));
        assert!(module.contains("pin = true"));
        assert!(!module.contains("effect = {"), "effects must be flat");
        assert!(module.contains("rounding = 0"));
        // Matched both ways: Wayland reports a class, XWayland is matched by title.
        assert!(module.contains("class = \"lennette\""));
        assert!(module.contains("title = \"lennette\""));
        assert!(module.contains("class = \"dev.lennette.overlay\""));
    }

    #[test]
    fn commands_map_to_distinct_actions() {
        let mut seen = std::collections::HashSet::new();
        for action in Action::ALL {
            assert!(seen.insert(command(action)), "duplicate for {action:?}");
            assert!(command(action).starts_with("lennette --"));
        }
    }

    #[test]
    fn the_required_line_matches_the_module_name() {
        assert!(required_line().contains("lennette"));
    }

    #[test]
    fn include_path_is_inside_the_directory() {
        let path = include_path(Path::new("/tmp/hypr"));
        assert_eq!(path, Path::new("/tmp/hypr/lennette.lua"));
    }
}
